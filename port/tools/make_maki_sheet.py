"""Pack the Maki pictograms into the sprite sheet compiled into fvkit.

Reads every <name>.png in testdata/GeoSymbol/makiPng (Maki, CC0) and writes
port/fvkit/symbol/maki_sheet.inc: the sheet PNG as a byte array and its
sprite.json index as a string. Each sprite is marked "sdf": the engine draws it
as an alpha mask tinted by icon-color. The 32 px tiles are pixelRatio 2, so an
icon at icon-size 1 is 16 px, near Maki's 15 px design size.

    python3 port/tools/make_maki_sheet.py            # from the repo root
    python3 port/tools/make_maki_sheet.py SRC_DIR    # another icon folder

Rerun after changing the icon set; do not edit maki_sheet.inc by hand.
"""

import io
import json
import os
import sys

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SRC = os.path.join(ROOT, "testdata", "GeoSymbol", "makiPng")
OUT = os.path.join(ROOT, "port", "fvkit", "symbol", "maki_sheet.inc")
COLUMNS = 16
GAP = 2  # transparent pixels between tiles, so filtering never reads a neighbour


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else SRC
    names = sorted(f[:-4] for f in os.listdir(src) if f.endswith(".png") and "@" not in f)
    if not names:
        sys.exit("no icons in " + src)
    tiles = [Image.open(os.path.join(src, n + ".png")).convert("RGBA") for n in names]
    cell_w = max(t.width for t in tiles) + GAP
    cell_h = max(t.height for t in tiles) + GAP
    rows = (len(tiles) + COLUMNS - 1) // COLUMNS
    sheet = Image.new("RGBA", (COLUMNS * cell_w, rows * cell_h), (0, 0, 0, 0))
    index = {}
    for i, (name, tile) in enumerate(zip(names, tiles)):
        x, y = (i % COLUMNS) * cell_w, (i // COLUMNS) * cell_h
        sheet.paste(tile, (x, y))
        index[name] = {"x": x, "y": y, "width": tile.width, "height": tile.height,
                       "pixelRatio": 2, "sdf": True}

    png = io.BytesIO()
    sheet.save(png, format="PNG", optimize=True)
    data = png.getvalue()
    text = json.dumps(index, sort_keys=True, separators=(",", ":"))

    with open(OUT, "w") as out:
        out.write("// Generated by port/tools/make_maki_sheet.py from the Maki icon set (CC0).\n")
        out.write("// Do not edit; rerun the script.\n\n")
        out.write("constexpr unsigned char kMakiSheetPng[] = {\n")
        for i in range(0, len(data), 20):
            out.write("  " + ",".join(str(b) for b in data[i:i + 20]) + ",\n")
        out.write("};\n\n")
        out.write("constexpr char kMakiSheetJson[] =\n")
        for i in range(0, len(text), 100):
            out.write("    " + json.dumps(text[i:i + 100]) + "\n")
        out.write(";\n")
    print("%d icons, sheet %dx%d, %d bytes PNG -> %s" % (len(names), sheet.width, sheet.height,
                                                        len(data), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
