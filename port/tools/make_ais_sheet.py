"""Pack FalconView's AIS ship symbols into the sprite sheet compiled into fvkit.

With a FalconView RTT/AIS directory as the argument, copies its hull PNGs into
port/fvkit/ais/symbols/ downscaled to 64 px long (pixelRatio 2), with lower-case
names, together with Symbollist.txt. Without an argument, rebuilds from that
in-tree copy. Writes port/fvkit/ais/ais_sheet.inc: the sheet PNG, its sprite.json
index, and the ITU ship-type to symbol table from Symbollist.txt's two-digit
keys (file names matched case-insensitively, as Windows did).

Each hull appears twice: `ais-<name>` as drawn, and `ais-<name>-stale` faded
for vessels not heard recently. Not SDF: the colour is the symbol.

    python3 port/tools/make_ais_sheet.py ~/Downloads/fvw511_data/.../RTT/AIS
    python3 port/tools/make_ais_sheet.py

Rerun after changing the symbols; do not edit ais_sheet.inc by hand.
"""

import io
import json
import os
import re
import shutil
import sys

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
TREE = os.path.join(ROOT, "port", "fvkit", "ais", "symbols")
OUT = os.path.join(ROOT, "port", "fvkit", "ais", "ais_sheet.inc")
HULL_PX = 64        # tile length along the hull, at pixelRatio 2
COLUMNS = 12
GAP = 2             # transparent pixels between tiles
SKIP = {"vessels", "lookout"}  # a contact sheet, and a decorator for unported lookouts
DEFAULT = "orange"


def canonical(name):
    """Symbol name from a file name: lower case, no extension, '-' for punctuation."""
    return re.sub(r"[^a-z0-9]+", "-", os.path.splitext(name)[0].lower()).strip("-")


def faded(tile):
    """The stale variant: halfway to grey, at half opacity."""
    r, g, b, a = tile.split()
    grey = Image.merge("RGB", (r, g, b)).convert("L").convert("RGB")
    rgb = Image.blend(Image.merge("RGB", (r, g, b)), grey, 0.6)
    a = a.point(lambda v: v // 2)
    return Image.merge("RGBA", (*rgb.split(), a))


def import_from(src):
    os.makedirs(TREE, exist_ok=True)
    for f in sorted(os.listdir(src)):
        if not f.lower().endswith(".png") or canonical(f) in SKIP:
            continue
        im = Image.open(os.path.join(src, f)).convert("RGBA")
        im = im.crop(im.getchannel("A").getbbox())
        w = max(1, round(im.width * HULL_PX / im.height))
        im.resize((w, HULL_PX), Image.LANCZOS).save(os.path.join(TREE, canonical(f) + ".png"),
                                                    optimize=True)
    shutil.copyfile(os.path.join(src, "Symbollist.txt"), os.path.join(TREE, "Symbollist.txt"))


def ship_type_table(names):
    """ITU ship type (0-99) to symbol name, from Symbollist.txt's two-digit keys."""
    table = [None] * 100
    with open(os.path.join(TREE, "Symbollist.txt"), encoding="latin-1") as f:
        for line in f:
            if line.startswith(";"):
                continue
            m = re.match(r"\s*(\d+)\s*[ ,|]\s*(\S+)", line)
            if not m or len(m.group(1)) > 2:
                continue  # three- and four-digit keys are MISLE display codes
            name = canonical(m.group(2))
            if name not in names:
                sys.exit("Symbollist.txt names %s, which is not in %s" % (m.group(2), TREE))
            table[int(m.group(1))] = name
    return table


def main():
    if len(sys.argv) > 1:
        import_from(sys.argv[1])
    names = sorted(canonical(f) for f in os.listdir(TREE) if f.endswith(".png"))
    if DEFAULT not in names:
        sys.exit("no %s.png in %s" % (DEFAULT, TREE))
    tiles = []
    for n in names:
        t = Image.open(os.path.join(TREE, n + ".png")).convert("RGBA")
        tiles.append(("ais-" + n, t))
        tiles.append(("ais-" + n + "-stale", faded(t)))

    cell_w = max(t.width for _, t in tiles) + GAP
    cell_h = max(t.height for _, t in tiles) + GAP
    rows = (len(tiles) + COLUMNS - 1) // COLUMNS
    sheet = Image.new("RGBA", (COLUMNS * cell_w, rows * cell_h), (0, 0, 0, 0))
    index = {}
    for i, (sid, tile) in enumerate(tiles):
        x, y = (i % COLUMNS) * cell_w, (i // COLUMNS) * cell_h
        sheet.paste(tile, (x, y))
        index[sid] = {"x": x, "y": y, "width": tile.width, "height": tile.height,
                      "pixelRatio": 2, "pivot_x": tile.width / 2, "pivot_y": tile.height / 2}

    png = io.BytesIO()
    sheet.save(png, format="PNG", optimize=True)
    data = png.getvalue()
    text = json.dumps(index, sort_keys=True, separators=(",", ":"))
    table = ship_type_table(set(names))

    with open(OUT, "w") as out:
        out.write("// Generated by port/tools/make_ais_sheet.py from FalconView's AIS ship symbols\n")
        out.write("// (port/fvkit/ais/symbols). Do not edit; rerun the script.\n\n")
        out.write("constexpr unsigned char kAisSheetPng[] = {\n")
        for i in range(0, len(data), 20):
            out.write("  " + ",".join(str(b) for b in data[i:i + 20]) + ",\n")
        out.write("};\n\n")
        out.write("constexpr char kAisSheetJson[] =\n")
        for i in range(0, len(text), 100):
            out.write("    " + json.dumps(text[i:i + 100]) + "\n")
        out.write(";\n\n")
        out.write("constexpr int kAisHullLengthTilePx = %d;\n\n" % HULL_PX)
        out.write("/// Symbol name by ITU ship type 0-99; null falls back to \"%s\".\n" % DEFAULT)
        out.write("constexpr const char* kAisShipTypeSymbol[100] = {\n")
        for i in range(0, 100, 5):
            out.write("    " + ", ".join(json.dumps(n) if n else "nullptr"
                                         for n in table[i:i + 5]) + ",\n")
        out.write("};\n")
    print("%d symbols, sheet %dx%d, %d bytes PNG -> %s" % (len(names), sheet.width, sheet.height,
                                                          len(data), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
