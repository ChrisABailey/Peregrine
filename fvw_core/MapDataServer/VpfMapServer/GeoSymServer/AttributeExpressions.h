////////////////////////////////////////////////////////////////////////////////
// Method: Evaluate
////////////////////////////////////////////////////////////////////////////////
inline
bool CAEEntry::Evaluate(const CAEAttributeList& aeAttributes) const
{
  // Assume the worst
  bool bResult = false;

  // Now get the value for the given attribute
  const CAEValue* pValTest = aeAttributes.GetValue(m_strAttribute+'=');

  // See if we at least have this value
  if (NULL != pValTest)
  {
    // We need a new compare mechanism
    if (CAEValue::AEVT_ATTRIB != m_value.ValueType())
    {
      // We have a simple compare
      bResult = pValTest->Compare(m_value, m_oper);
    }
    else
    {
      // We need to get the other value so we need to copy
      // val test since it is temporary
      CAEValue valTest = *pValTest;
      const CAEValue* pValComp = aeAttributes.GetValue(m_value.StringValue());
      if (NULL != pValComp)
      {
        bResult = valTest.Compare(*pValComp, m_oper);
      }
    }
  }

  return bResult;
}

