//Method:      Ordinal
//////////////////////////////////////////////////////////////////////////////
inline
void CStringToOrdinal::CopyFieldString(TCHAR*  szDest,
                                       LPCTSTR szSrc,
                                       long    nLength)
{
  long nBestLength = (EN_FIELD_NAME_SIZE <= nLength) ?
                      EN_FIELD_NAME_SIZE : nLength;
  TRACE(_T("This code requires testing due to security changes (Line %d File %s).  Remove this message after this line has been executed."), __LINE__, __FILE__);
  ::_tcsncpy_s(szDest, nBestLength, szSrc, nBestLength);
  szDest[nBestLength] = _T('\0');
}

