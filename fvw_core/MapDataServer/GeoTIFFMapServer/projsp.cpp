// convert FalconView datum string codes to gctpc datum codes

int CProj::string_to_datum(std::string datum_str, long *datum)
{
	std::string dat;

//	dat = datum_str.Left(3);
	dat = datum_str.substr(0, 3);

	// GRS 1980
	if (!dat.compare("W84")
		|| !dat.compare("NAR")
		|| !dat.compare("KOR"))
	{
		*datum = 8;  // GRS 1980
		return SUCCESS;
	}

	// WGS 72
	if (!dat.compare("W72"))
	{
		*datum = 5;  // WGS 72
		return SUCCESS;
	}

	// WGS 66
	if (!dat.compare("W66"))
	{
		*datum = 7;  // WGS 66
		return SUCCESS;
	}

	// Clark 1880
	if (!dat.compare("ADI")
		|| !dat.compare("AIA")
		|| !dat.compare("ARF")
		|| !dat.compare("ARS")
		|| !dat.compare("ASM")
		|| !dat.compare("CAP")
		|| !dat.compare("CGE")
		|| !dat.compare("DAL")
		|| !dat.compare("DID")
		|| !dat.compare("FAH")
		|| !dat.compare("FOT")
		|| !dat.compare("LEH")
		|| !dat.compare("LIB")
		|| !dat.compare("MER")
		|| !dat.compare("MIK")
		|| !dat.compare("MIN")
		|| !dat.compare("MPO")
		|| !dat.compare("MVS")
		|| !dat.compare("NAH")
		|| !dat.compare("NSD")
		|| !dat.compare("PHA")
		|| !dat.compare("PTB")
		|| !dat.compare("PTN")
		|| !dat.compare("SRL")
		|| !dat.compare("VOI")
		|| !dat.compare("VOR"))
	{
		*datum = 1;  // Clark 1880
		return SUCCESS;
	}

	// Bessel
	if (!dat.compare("BAT")
		|| !dat.compare("BUR")
		|| !dat.compare("CCD")
		|| !dat.compare("GSE")
		|| !dat.compare("MAS")
		|| !dat.compare("TOY"))
	{
		*datum = 2;  // Bessel
		return SUCCESS;
	}

	// International 1967
	if (!dat.compare("IDN"))
	{
		*datum = 3;  // International 1967 (Indonesian 1974 is the closest fit)
		return SUCCESS;
	}

	// International 1909
	if (!dat.compare("AIN")
		|| !dat.compare("ASC")
		|| !dat.compare("ASQ")
		|| !dat.compare("ATF")
		|| !dat.compare("BID")
		|| !dat.compare("BOO")
		|| !dat.compare("CAI")
		|| !dat.compare("CAO")
		|| !dat.compare("CAZ")
		|| !dat.compare("CHI")
		|| !dat.compare("COA")
		|| !dat.compare("DOB")
		|| !dat.compare("EAS")
		|| !dat.compare("EUR")
		|| !dat.compare("EUS")
		|| !dat.compare("FLO")
		|| !dat.compare("GAA")
		|| !dat.compare("GEO")
		|| !dat.compare("GIZ")
		|| !dat.compare("GRA")
		|| !dat.compare("HEN")
		|| !dat.compare("HIT")
		|| !dat.compare("HJO")
		|| !dat.compare("HKD")
		|| !dat.compare("HTN")
		|| !dat.compare("IBE")
		|| !dat.compare("ISG")
		|| !dat.compare("IST")
		|| !dat.compare("JOH")
		|| !dat.compare("KEG")
		|| !dat.compare("KUS")
		|| !dat.compare("MID")
		|| !dat.compare("MOD")
		|| !dat.compare("NAP")
		|| !datum_str.compare("OHA-P")
		|| !datum_str.compare("OHA-Q")
		|| !datum_str.compare("OHA-R")
		|| !dat.compare("PIT")
		|| !dat.compare("PLN")
		|| !dat.compare("POS")
		|| !dat.compare("PRP")
		|| !dat.compare("QAT")
		|| !dat.compare("QUO")
		|| !dat.compare("REU")
		|| !dat.compare("SAE")
		|| !dat.compare("SAO")
		|| !dat.compare("SAP")
		|| !dat.compare("SCK")
		|| !dat.compare("SGM")
		|| !dat.compare("SHB")
		|| !dat.compare("TAN")
		|| !dat.compare("TDC")
		|| !dat.compare("TRN")
		|| !dat.compare("WAK")
		|| !dat.compare("YAC")
		|| !dat.compare("ZAN"))
	{
		*datum = 4;  // International 1967
		return SUCCESS;
	}

	// Clark 1866 (this must to after the International 1967 due to OHA)
	if (!dat.compare("NAS")
		|| !dat.compare("AMA")
		|| !dat.compare("BER")
		|| !dat.compare("CAC")
		|| !dat.compare("GUA")
		|| !dat.compare("LCF")
		|| !dat.compare("LUZ")
		|| !dat.compare("OHA")
		|| !dat.compare("PUR"))
	{
		*datum = 0;  // Clark 1866
		return SUCCESS;
	}

	// Everest
	if (!dat.compare("IND")
		|| !dat.compare("INF")
		|| !dat.compare("ING")
		|| !dat.compare("INF")
		|| !dat.compare("INH")
		|| !dat.compare("KAN")
		|| !dat.compare("TIL"))
	{
		*datum = 6;  // Everest (actually Everest 1956)
		return SUCCESS;
	}

	// Airy
	if (!dat.compare("OGB"))
	{
		*datum = 9;  // Airy (actually Airy 1830)
		return SUCCESS;
	}

	// Modified Everest
	if (!dat.compare("KEA"))
	{
		*datum = 10;  // Modified Everest (actually Everest 1948)
		return SUCCESS;
	}

	// Modified Airy
	if (!dat.compare("IRL"))
	{
		*datum = 11;  // Modified Airy
		return SUCCESS;
	}

	// Southeast Asia
	if (!dat.compare("SOA"))
	{
		*datum = 13;  // Southeast Asia (actually Modified Fisher 1960)
		return SUCCESS;
	}

	// Australian National
	if (!dat.compare("ANO")
		|| !dat.compare("AUA")
		|| !dat.compare("AUG"))
	{
		*datum = 14;  // Australian National
	}

	// Krassovsky
	if (!dat.compare("PUK")
		|| !dat.compare("SPK")
		|| !dat.compare("AFG"))
	{
		*datum = 15;  // Krassovsky
		return SUCCESS;
	}

	// Hough
	if (!dat.compare("ENW"))
	{
		*datum = 16;  // Hough (actually Hough 1960)
		return SUCCESS;
	}

	// Mercury 1960 (actually Fisher 1960) (not used by any datum that FalconView supports)
	// Modified Mercury is the same as Modified Fisher 1960

	*datum = 0;

	return FAILURE;
}
