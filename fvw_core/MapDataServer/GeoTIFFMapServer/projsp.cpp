/* Function to compute the latitude angle, phi2, for the inverse of the
   Lambert Conformal Conic and Polar Stereographic projections.
----------------------------------------------------------------*/
double CProj::phi2z(double eccent,  /* Spheroid eccentricity		*/
					 double ts,		/* Constant value t			*/
					 long *flag)	/* Error flag number			*/
{
	double eccnth;
	double phi;
	double con;
	double dphi;
	double sinpi;
	long i;

	*flag = 0;
	eccnth = .5 * eccent;
	phi = HALF_PI - 2 * atan(ts);
	for (i = 0; i <= 15; i++)
	{
		sinpi = sin(phi);
		con = eccent * sinpi;
		dphi = HALF_PI - 2 * atan(ts *(pow(((1.0 - con)/(1.0 + con)),eccnth))) - 
		phi;
		phi += dphi; 
		if (fabs(dphi) <= .0000000001)
			return(phi);
	}
	m_last_error = "Convergence error","phi2z-conv";
	*flag = 002;
	return(002);
}
 
