// Albers Conical Equal Area inverse equations--mapping x,y to lat/long

int CProj::alberinv(double x, double y, double *lon, double *lat)
{
	double rh1;			// height above ellipsoid
	double qs;			// function q
	double con;			// temporary sign value
	double theta;		// angle
	long   flag;		// error flag


	flag = 0;
	x -= false_easting;
	y = rh - y + false_northing;;
	if (ns0 >= 0)
	{
		rh1 = sqrt(x * x + y * y);
		con = 1.0;
	}
	else
	{
		rh1 = -sqrt(x * x + y * y);
		con = -1.0;
	}
	theta = 0.0;
	if (rh1 != 0.0)
		theta = atan2(con * x, con * y);
	con = rh1 * ns0 / r_major;
	qs = (c - con * con) / ns0;
	if (e3 >= 1e-10)
	{
		con = 1 - .5 * (1.0 - es) * log((1.0 - e3) / (1.0 + e3))/e3;
		if (fabs(fabs(con) - fabs(qs)) > .0000000001 )
		{
			*lat = phi1z(e3, qs, &flag);
			if (flag != 0)
				return(flag);
		}
		else
		{
			if (qs >= 0)
			*lat = .5 * PI;
			else
			*lat = -.5 * PI;
		}
	}
	else
	{
		*lat = phi1z(e3, qs, &flag);
		if (flag != 0)
			return(flag);
	}

	*lon = adjust_lon(theta/ns0 + lon_center);

	return SUCCESS;
}

