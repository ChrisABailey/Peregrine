/* Function to compute phi1, the latitude for the inverse of the
   Albers Conical Equal-Area projection.
-------------------------------------------*/
double CProj::phi1z (double eccent,	// Eccentricity angle in radians
					  double qs,		// Angle in radians	
					  long  *flag)		// Error flag number
{
	double eccnts;
	double dphi;
	double con;
	double com;
	double sinpi;
	double cospi;
	double phi;
	long i;

	*flag = 0;
	phi = asinz(.5 * qs);
	if (eccent < EPSLN) 
		return(phi);
	eccnts = eccent * eccent; 
	for (i = 1; i <= 25; i++)
	{
		sincos(phi,&sinpi,&cospi);
		con = eccent * sinpi; 
		com = 1.0 - con * con;
		dphi = .5 * com * com / cospi * (qs / (1.0 - eccnts) - sinpi / com + 
				.5 / eccent * log ((1.0 - con) / (1.0 + con)));
		phi = phi + dphi;
		if (fabs(dphi) <= 1e-7)
			return(phi);
	}
	m_last_error = "Convergence error","phi1z-conv";
	*flag = 001;
	return(ERROR);
}

