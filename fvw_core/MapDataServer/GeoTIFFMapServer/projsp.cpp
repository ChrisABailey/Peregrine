// Oblique Mercator inverse equations--mapping x,y to lat/long

int CProj::omerinv(double x, double y, double *lon, double *lat)
{
	double theta;		
	double t;	
	double con;
	double vs,us,q,s,ts1;
	double vl,ul;
	long   flag;

	// Inverse equations
	x -= false_easting;
	y -= false_northing;
	flag = 0;
	vs = x * cosaz - y * sinaz;
	us = y * cosaz + x * sinaz;
	us = us + u;
	q = exp(-bl * vs / al);
	s = .5 * (q - 1.0/q);
	t = .5 * (q + 1.0/q);
	vl = sin(bl * us / al);
	ul = (vl * cosgam + s * singam)/t;
	if (fabs(fabs(ul) - 1.0) <= EPSLN)
	{
		*lon = lon_origin;
		if (ul >= 0.0)
			*lat = HALF_PI;
		else
			*lat = -HALF_PI;
	}
	else
	{
		con = 1.0 / bl;
		ts1 = pow((el / sqrt((1.0 + ul) / (1.0 - ul))),con);
		*lat = phi2z(e,ts1,&flag);
		if (flag != 0)
			return FAILURE;
		con = cos(bl * us /al);
		theta = lon_origin - atan2((s * cosgam - vl * singam) , con)/bl;
		*lon = adjust_lon(theta);
	}
	return SUCCESS;
}

