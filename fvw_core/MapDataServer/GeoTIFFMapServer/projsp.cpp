/* Function to compute, phi4, the latitude for the inverse of the
   Polyconic projection.
------------------------------------------------------------*/
int CProj::phi4z (double eccent,double e0,double e1,double e2,double e3,double a,double b,double *c,double *phi) 
{
	double sinphi;
	double sin2ph;
	double tanphi;
	double ml;
	double mlp;
	double con1;
	double con2;
	double con3;
	double dphi;
	long i;

	*phi = a;
	for (i = 1; i <= 15; i++)
	{
		sinphi = sin(*phi);
		tanphi = tan(*phi);
		*c = tanphi * sqrt (1.0 - eccent * sinphi * sinphi);
		sin2ph = sin (2.0 * *phi);
		ml = e0 * *phi - e1 * sin2ph + e2 * sin (4.0 *  *phi) - e3 * 
		sin (6.0 *  *phi);
		mlp = e0 - 2.0 * e1 * cos (2.0 *  *phi) + 4.0 * e2 *
		cos (4.0 *  *phi) - 6.0 * e3 * cos (6.0 *  *phi);
		con1 = 2.0 * ml + *c * (ml * ml + b) - 2.0 * a *  (*c * ml + 1.0);
		con2 = eccent * sin2ph * (ml * ml + b - 2.0 * a * ml) / (2.0 * *c);
		con3 = 2.0 * (a - ml) * (*c * mlp - 2.0 / sin2ph) - 2.0 * mlp;
		dphi = con1 / (con2 + con3);
		*phi += dphi;
		if (fabs(dphi) <= .0000000001 )
			return SUCCESS;
	}
	m_last_error = "Lattitude failed to converge","phi4z-conv";
	return FAILURE;
}

