/* Transverse Mercator inverse equations--mapping x,y to lat,long 
   Note:  The algorithm for UTM is exactly the same as TM and therefore
          if a change is implemented, also make the change to UTMINV.c
  --------------------------------------------------------------*/
int CProj::tminv(double x, double y, double *lon, double *lat)
{
	double con,phi;		/* temporary angles				*/
	double delta_phi;	/* difference between longitudes		*/
	long i;			/* counter variable				*/
	double sin_phi, cos_phi, tan_phi;	/* sin cos and tangent values	*/
	double c, cs, t, ts, n, r, d, ds;	/* temporary variables		*/
	double f, h, g, temp;			/* temporary variables		*/
	long max_iter = 6;			/* maximun number of iterations	*/

	/* fortran code for spherical form 
	--------------------------------*/
	if (ind != 0)
	{
		f = exp(x/(r_major * scale_factor));
		g = .5 * (f - 1/f);
		temp = lat_origin + y/(r_major * scale_factor);
		h = cos(temp);
		con = sqrt((1.0 - h * h)/(1.0 + g * g));
		*lat = asinz(con);
		if (temp < 0)
			*lat = -*lat;
		if ((g == 0) && (h == 0))
		{
			*lon = lon_center;
			return SUCCESS;
		}
		else
		{
			*lon = adjust_lon(atan2(g,h) + lon_center);
			return SUCCESS;
		}
	}

	/* Inverse equations
	-----------------*/
	x = x - false_easting;
	y = y - false_northing;

	con = (ml0 + y / scale_factor) / r_major;
	phi = con;
	for (i=0;;i++)
	{
		delta_phi = ((con + e1 * sin(2.0*phi) - e2 * sin(4.0*phi) + e3 * sin(6.0*phi)) / e0) - phi;
		phi += delta_phi;
		if (fabs(delta_phi) <= EPSLN) 
			break;
		if (i >= max_iter) 
		{ 
			m_last_error = "Latitude failed to converge in tm inverse"; 
			return FAILURE;
		}
	}
	if (fabs(phi) < HALF_PI)
	{
		sincos(phi, &sin_phi, &cos_phi);
		tan_phi = tan(phi);
		c    = esp * SQUARE(cos_phi);
		cs   = SQUARE(c);
		t    = SQUARE(tan_phi);
		ts   = SQUARE(t);
		con  = 1.0 - es * SQUARE(sin_phi); 
		n    = r_major / sqrt(con);
		r    = n * (1.0 - es) / con;
		d    = x / (n * scale_factor);
		ds   = SQUARE(d);
		*lat = phi - (n * tan_phi * ds / r) * (0.5 - ds / 24.0 * (5.0 + 3.0 * t + 
				10.0 * c - 4.0 * cs - 9.0 * esp - ds / 30.0 * (61.0 + 90.0 * t +
				298.0 * c + 45.0 * ts - 252.0 * esp - 3.0 * cs)));
		*lon = adjust_lon(lon_center + (d * (1.0 - ds / 6.0 * (1.0 + 2.0 * t +
				c - ds / 20.0 * (5.0 - 2.0 * c + 28.0 * t - 3.0 * cs + 8.0 * esp +
				24.0 * ts))) / cos_phi));
	}
	else
	{
		*lat = HALF_PI * sign(y);
		*lon = lon_center;
	}
	return SUCCESS;
}

