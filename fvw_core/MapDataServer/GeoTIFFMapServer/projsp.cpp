/* Function to compute latitude, phi3, for the inverse of the Equidistant
   Conic projection.
-----------------------------------------------------------------*/
double CProj::phi3z(double ml,double e0,double e1,double e2,double e3, long *flag)
{
	double phi;
	double dphi;
	long i;

	phi = ml;
	for (i = 0; i < 15; i++)
	{
		dphi = (ml + e1 * sin(2.0 * phi) - e2 * sin(4.0 * phi) + e3 * sin(6.0 * phi)) / e0 - phi;
		phi += dphi;
		if (fabs(dphi) <= .0000000001)
		{
			*flag = 0;
			return (phi);
		}
	}
	m_last_error = "Latitude failed to converge after 15 iterations","PHI3Z-CONV";
	*flag = 3;
	return(3);
}

