/* Initialize the Universal Transverse Mercator (UTM) projection
  -------------------------------------------------------------*/
int CProj::utminvint(double r_maj, double r_min, double scale_fact, long zone)
{
	double temp;			/* temprorary variables			*/

	if ((abs(zone) < 1) || (abs(zone) > 60))
	{
		m_last_error = "Illegal zone number in utm-invint";
		return FAILURE;
	}
	r_major = r_maj;
	r_minor = r_min;
	scale_factor = scale_fact;
	lat_origin = 0.0;
	lon_center = ((6 * abs(zone)) - 183) * D2R;
	false_easting = 500000.0;
	false_northing = (zone < 0) ? 10000000.0 : 0.0;

	temp = r_minor / r_major;
	es = 1.0 - SQUARE(temp);
	e = sqrt(es);
	e0 = e0fn(es);
	e1 = e1fn(es);
	e2 = e2fn(es);
	e3 = e3fn(es);
	ml0 = r_major * mlfn(e0, e1, e2, e3, lat_origin);
	esp = es / (1.0 - es);

	if (es < .00001)
		ind = 1;
	else 
		ind = 0;

	return SUCCESS;
}

