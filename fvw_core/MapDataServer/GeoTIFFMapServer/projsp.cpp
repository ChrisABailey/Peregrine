// Lambert Conformal Conic inverse equations--mapping x,y to lat/long

int CProj::lamccinv(double x , double y, double *lon, double *lat)
{
	double rh1;			// height above ellipsoid
	double con;			// sign variable
	double ts;			// small t
	double theta;		// angle
	long   flag;		// error flag

	flag = 0;
	x -= false_easting;
	y = rh - y + false_northing;
	if (ns > 0)
	{
		rh1 = sqrt (x * x + y * y);
		con = 1.0;
	}
	else
	{
		rh1 = -sqrt (x * x + y * y);
		con = -1.0;
	}
	theta = 0.0;
	if (rh1 != 0)
		theta = atan2((con * x),(con * y));
	if ((rh1 != 0) || (ns > 0.0))
	{
		con = 1.0/ns;
		ts = pow((rh1/(r_major * f0)),con);
		*lat = phi2z(e,ts,&flag);
		if (flag != 0)
			return(flag);
	}
	else
		*lat = -HALF_PI;

	*lon = adjust_lon(theta/ns + center_lon);

	return SUCCESS;
 }

