{
	if (!m_initialized)
		return FAILURE;

	double in_coord[2];
	double out_coord[2];
	long zero = 0;
	long print_debug_info = 3;
	int rslt;
	long outsys;

	in_coord[0] = x;
	in_coord[1] = y;

	m_in_units = m_state_units;
	m_out_units = PROJ_UNITS_DEGREES;
	outsys = PROJ_TYPE_GEO;

	rslt = convert(in_coord, &m_proj_type, &m_zone, &m_in_units, &m_datum,
				out_coord, &outsys, &m_zone, &m_out_units, &m_datum);

	*lat = out_coord[1];
	*lon = out_coord[0];

	return rslt;
}


