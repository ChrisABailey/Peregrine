/* Convert DMS packed angle into deg 
----------------------------------*/
double CProj::paksz(double ang, long *iflg)
{
	double fac;		/* sign flag			*/
	double deg;		/* degree variable		*/
	double min;		/* minute variable		*/
	double sec;		/* seconds variable		*/
	double tmp;		/* temporary variable		*/
	long i;			/* temporary variable		*/

	*iflg = 0;

	if (ang < 0.0)
		fac = -1;
	else
		fac = 1;

	/* find degrees
	-------------*/
	sec = fabs(ang);
	tmp = 1000000.0;
	i = (long) (sec/tmp);
	if (i > 360)
	{
		m_last_error = "Illegal DMS field in paksz-deg";
		*iflg = 1116;
		return(ERROR);
	}
	else
		deg = i;

	// find minutes
	sec = sec - deg * tmp;
	tmp = 1000;
	i = (long) (sec / tmp);
	if (i > 60)
	{
		m_last_error = "Illegal DMS field in paksz-min";
		*iflg = 1116;
		return(ERROR);
	}
	else
		min = i;

	// find seconds
	sec = sec - min * tmp;
	if (sec > 60)
	{
		m_last_error = "Illegal DMS field in paksz-sec";
		*iflg = 1116;
		return(ERROR);
	}
	else
	sec = fac * (deg * 3600.0 + min * 60.0 + sec);
	deg = sec / 3600.0;

	return(deg);
}



