// Oblique Mercator forward equations--mapping lat,long to x,y

int CProj::omerfor(double lon, double lat, double *x, double *y)
{
	double sin_phi;/* sin and cos value				*/
	double t;	/* temporary values				*/
	double con;	/* cone constant, small m			*/
	double q,us,vl;
	double ul,vs;
	double s;
	double dlon;
	double ts1;

	// Forward equations
	sin_phi = sin(lat);
	dlon = adjust_lon(lon - lon_origin);
	vl = sin(bl * dlon);
	if (fabs(fabs(lat) - HALF_PI) > EPSLN)
	{
		ts1 = tsfnz(e,lat,sin_phi);
		q = el / (pow(ts1,bl));
		s = .5 * (q - 1.0 / q);
		t = .5 * (q + 1.0/ q);
		ul = (s * singam - vl * cosgam) / t;
		con = cos(bl * dlon);
		if (fabs(con) < .0000001)
		{
			us = al * bl * dlon;
		}
		else
		{
			us = al * atan((s * cosgam + vl * singam) / con)/bl;
			if (con < 0)
			us = us + PI * al / bl;
		}
	}
	else
	{
		if (lat >= 0)
			ul = singam;
		else
			ul = -singam;
		us = al * lat / bl;
	}
	if (fabs(fabs(ul) - 1.0) <= EPSLN)
	{
		m_last_error = "Point projects into infinity in omer-for";
		return FAILURE;
	}
	vs = .5 * al * log((1.0 - ul)/(1.0 + ul)) / bl;
	us = us - u;
	*x = false_easting + vs * cosaz + us * sinaz;
	*y = false_northing + us * cosaz - vs * sinaz;

	return SUCCESS;
}

