// returns the units code for a sp fips zone and spheroid
// sphere: NAD27 = 0, NAD83 = 8
// units: us survey feet = 1, meters = 2, international feet = 5

int CProj::get_sp_units_from_zone(long fips_zone, long sphere)
{
	int k = 0;
	int found = 0;

	if (sphere == 0)
	{
		// search nad27
		while ((k < 133) && (found == 0))
		{
			if (fips_zone == nad27dat[k].code)
				return nad27dat[k].units;
			k++;
		}
	}
	else
	{
		// search nad83
		while ((k < 133) && (found == 0))
		{
			if (fips_zone == nad83dat[k].code)
				return nad83dat[k].units;
			k++;
		}
	}

	return 0;
}

