// Initialize the Lambert Conformal Conic projection

int CProj::lamccinvint(double r_maj, double r_min,
			double  lat1,	// first standard parallel
			double lat2,	// second standard parallel
			double c_lon, double c_lat,  // center lat and long
			double false_east, double false_north)  // offsets in meters
{
	double sin_po;			// sin value
	double cos_po;			// cos value
	double con;				// temporary sin value	
	double ms1;				// small m 1
	double ms2;				// small m 2		
	double temp;			// temporary variable	
	double ts0;				// small t 0		
	double ts1;				// small t 1	
	double ts2;				// small t 2	

	r_major = r_maj;
	r_minor = r_min;
	false_easting = false_east;
	false_northing = false_north;

	// Standard Parallels cannot be equal and on opposite sides of the equator
	if (fabs(lat1+lat2) < EPSLN)
	{
		m_last_error = "Equal Latitiudes for St. Parallels on opposite sides of equator in lamcc-inv";
		return FAILURE;
	}

	temp = r_minor / r_major;
	es = 1.0 - SQUARE(temp);
	e = sqrt(es);

	center_lon = c_lon;
	center_lat = c_lat;
	sincos(lat1,&sin_po,&cos_po);
	con = sin_po;
	ms1 = msfnz(e,sin_po,cos_po);
	ts1 = tsfnz(e,lat1,sin_po);
	sincos(lat2,&sin_po,&cos_po);
	ms2 = msfnz(e,sin_po,cos_po);
	ts2 = tsfnz(e,lat2,sin_po);
	sin_po = sin(center_lat);
	ts0 = tsfnz(e,center_lat,sin_po);

	if (fabs(lat1 - lat2) > EPSLN)
		ns = log (ms1/ms2)/ log (ts1/ts2);
	else
		ns = con;
	f0 = ms1 / (ns * pow(ts1,ns));
	rh = r_major * f0 * pow(ts0,ns);

	return SUCCESS;
}

