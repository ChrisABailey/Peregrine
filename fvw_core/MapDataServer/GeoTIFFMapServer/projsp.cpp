// Initialize the Oblique Mercator  projection

int CProj::omerinvint(double r_maj, double r_min,	// sp_major_axis and sp_minor_axis axis
				double scale_fact,			// scale factor
				double azimuth,				// azimuth east of north
				double lon_orig,			// longitude of origin
				double lat_orig,			// center latitude
				double false_east,			// x offset in meters
				double false_north,			// y offset in meters
				double lon1, double lat1,	// first point to define central line
				double lon2, double lat2,	// second point to define central line
				long mode)					// which type: A or B
{
	double temp;			// temporary variable
	double con,com;
	double h,l,ts1,ts2;
	double j,p,dlon;
	double f,g,gama;
	double sinphi;
	//double cosphi;

	// Place parameters in static storage for common use
	r_major = r_maj;
	r_minor = r_min;
	scale_factor = scale_fact;
	lat_origin = lat_orig;
	false_northing = false_north;
	false_easting = false_east;

	temp = r_minor / r_major;
	es = 1.0 - SQUARE(temp);
	e = sqrt(es);
	f = 1.0;

	sincos(lat_origin,&sin_p20,&cos_p20);
	con = 1.0 - es * sin_p20 * sin_p20;
	com = sqrt(1.0 - es);
	bl = sqrt(1.0 + es * pow(cos_p20,4.0)/(1.0 - es));
	al = r_major * bl * scale_factor * com / con;
	if (fabs(lat_origin) < EPSLN)
	{
		ts = 1.0;
		d = 1.0;
		el = 1.0;
	}
	else
	{
		ts = tsfnz(e,lat_origin,sin_p20);
		con = sqrt(con);
		d = bl * com / (cos_p20 * con);
		if ((d * d - 1.0) > 0.0)
		{
			if (lat_origin >= 0.0)
				f = d + sqrt(d * d - 1.0);
			else
				f = d - sqrt(d * d - 1.0);
		}
		else
			f = d;
		el = f * pow(ts,bl);
	}

	if (mode != 0)
	{
		g = .5 * (f - 1.0/f);
		gama = asinz(sin(azimuth) / d);
		lon_origin = lon_orig - asinz(g * tan(gama))/bl;

		con = fabs(lat_origin);
		if ((con > EPSLN) && (fabs(con - HALF_PI) > EPSLN))
		{
			sincos(gama,&singam,&cosgam);
			sincos(azimuth,&sinaz,&cosaz);
			if (lat_origin >= 0)
				u =  (al / bl) * atan(sqrt(d*d - 1.0)/cosaz);
			else
				u =  -(al / bl) * atan(sqrt(d*d - 1.0)/cosaz);
		}
		else
		{
			m_last_error = "Input data error in omer-init";
			return FAILURE;
		}
	}
	else
	{
		sinphi = sin(lat1);
		ts1 = tsfnz(e,lat1,sinphi);
		sinphi = sin(lat2);
		ts2 = tsfnz(e,lat2,sinphi);
		h = pow(ts1,bl);
		l = pow(ts2,bl);
		f = el/h;
		g = .5 * (f - 1.0/f);
		j = (el * el - l * h)/(el * el + l * h);
		p = (l - h) / (l + h);
		dlon = lon1 - lon2;
		if (dlon < -PI)
			lon2 = lon2 - 2.0 * PI;
		if (dlon > PI)
			lon2 = lon2 + 2.0 * PI;
		dlon = lon1 - lon2;
		lon_origin = .5 * (lon1 + lon2) - atan(j * tan(.5 * bl * dlon)/p)/bl;
		dlon  = adjust_lon(lon1 - lon_origin);
		gama = atan(sin(bl * dlon)/g);
		azimuth = asinz(d * sin(gama));

		if (fabs(lat1 - lat2) <= EPSLN)
		{
			m_last_error = "Input data error in omer-init";
			return FAILURE;
		}
		else
		con = fabs(lat1);
		if ((con <= EPSLN) || (fabs(con - HALF_PI) <= EPSLN))
		{
			m_last_error = "Input data error in omer-init";
			return FAILURE;
		}
		else 
		if (fabs(fabs(lat_origin) - HALF_PI) <= EPSLN)
		{
			m_last_error = "Input data error in omer-init";
			return FAILURE;
		}

		sincos(gama,&singam,&cosgam);
		sincos(azimuth,&sinaz,&cosaz);
		if (lat_origin >= 0)
			u =  (al/bl) * atan(sqrt(d * d - 1.0)/cosaz);
		else
			u = -(al/bl) * atan(sqrt(d * d - 1.0)/cosaz);
	}

	return SUCCESS;
}

