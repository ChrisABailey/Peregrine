int CProj::convert(double *incoor, // input coordinates				
					long *insys,	// input projection code
					long *inzone,	// input zone number
					long *inunit,	// input units
					long *inspheroid,	// input spheroid 
					double *outcoor,	// output coordinates
					long *outsys,		// output projection code
					long *outzone,		// output zone
					long *outunit,		// output units
					long *outspheroid)	// output spheroid

{
	double x;		/* x coordinate 				*/
	double y;		/* y coordinate					*/
	double factor;		/* conversion factor				*/
	double lon;		/* longitude					*/
	double lat;		/* latitude					*/
	//double temp;		/* temporary variable				*/
	long i/*,j*/;		/* loop counters				*/
	long ininit_flag;	/* input initilization flag			*/
	long outinit_flag;	/* output initilization flag			*/
	//long ind;		/* temporary var used to find state plane zone 	*/
	long unit;		/* temporary unit variable			*/
	double temparr[COEFCT];	/* temporary projection array 			*/
	long iflg;
	int rslt;

	/* setup initilization flags and output message flags
	---------------------------------------------------*/
	ininit_flag = FALSE;
	outinit_flag = FALSE;
	iflg = 0;

//	iflg = init(*ipr,*jpr,efile,pfile);
//	if (iflg != 0)
//	   return FAILURE;


	/* check to see if initilization is required
	only the first 13 projection parameters are currently used.
	If more are added the loop should be increased.
	---------------------------------------------------------*/
	if (iter == 0)
	{
		for (i = 0; i < MAXPROJ + 1; i++)
		{
			inpj[i] = 0;
			indat[i] = 0;
			inzn[i] = 0;
			outpj[i] = 0;
			outdat[i] = 0;
			outzn[i] = 0;
#if 1
         ZeroMemory( pdin, sizeof(pdin) );
         ZeroMemory( pdout, sizeof(pdout) );
#else
			for (j = 0; j < COEFCT; j++)
			{
				pdin[i][j] = 0.0;
				pdout[i][j] = 0.0;
			}
#endif
		}
		ininit_flag = TRUE;
		outinit_flag = TRUE;
		iter = 1;
	}
	else
	{
		if (*insys != PROJ_TYPE_GEO)
		{
			if ((inzn[*insys] != *inzone) || (indat[*insys] != *inspheroid) || (inpj[*insys] != *insys))
			{
				ininit_flag = TRUE;
			}
			else
				for (i = 0; i < 13; i++)
					if (pdin[*insys][i] != m_in_params[i])
					{
						ininit_flag = TRUE;
						break;
					}
		}
		if (*outsys != PROJ_TYPE_GEO)
		{
			if ((outzn[*outsys] != *outzone) || (outdat[*outsys] != *outspheroid) || (outpj[*outsys] != *outsys))
			{
				outinit_flag = TRUE;
			}
			else
				for (i = 0; i < 13; i++)
					if (pdout[*outsys][i] != m_out_params[i])
					{
						outinit_flag = TRUE;
						break;
					}
		}
	}

	/* Check input and output projection numbers
	------------------------------------------*/
	if ((*insys < PROJ_TYPE_GEO) || (*insys > MAXPROJ))
	{
		m_last_error = "Insys is illegal","GCTP-INPUT";
		iflg = 1;
		return FAILURE;
	}
	if ((*outsys < PROJ_TYPE_GEO) || (*outsys > MAXPROJ))
	{
		m_last_error = "Outsys is illegal","GCTP-OUTPUT";
		iflg = 2;
		return FAILURE;
	}

	/* find the correct conversion factor for units
	---------------------------------------------*/
	unit = *inunit;

	/* use legislated unit table for State Plane
	-------------------------------------------*/
	if ((*inspheroid == 0) && (*insys == PROJ_TYPE_SPCS) && (*inunit == STPLN_TABLE)) 
		unit = PROJ_UNITS_US_FEET;
	if ((*inspheroid == 8) && (*insys == PROJ_TYPE_SPCS) && (*inunit == STPLN_TABLE))
		unit = NADUT[(*inzone)/100];

	/* find the factor unit conversions--all transformations are in radians
	or meters
	--------------------------------*/
	if (*insys == PROJ_TYPE_GEO)
		iflg = untfz(unit, PROJ_UNITS_RADIAN, &factor); 
	else
		iflg = untfz(unit, PROJ_UNITS_METERS, &factor); 
	if (*insys == PROJ_TYPE_SPCS)
		*inunit = unit;
	if (iflg != 0)
	{
//		close_file();
		return FAILURE;
	}
 
	x = incoor[0] * factor;
	y = incoor[1] * factor;

/* Initialize inverse transformation
----------------------------------*/
	if (ininit_flag)
	{
		inpj[*insys] = *insys;
		indat[*insys] = *inspheroid;
		inzn[*insys] = *inzone;
		for (i = 0;i < COEFCT; i++)
			pdin[*insys][i] = m_in_params[i];

		/* Call the initialization function
		----------------------------------*/
		inv_init(*insys, *inzone, m_in_params, *inspheroid,	&iflg);
		if (iflg != 0)
		{
//			close_file();
			return FAILURE;
		}
	}

	/* Do actual transformations
	--------------------------*/

	/* Inverse transformations
	------------------------*/
	if (*insys == PROJ_TYPE_GEO)
	{
		lon = x;
		lat = y;
	}
	else
	{
		rslt = inverse_trans(x, y, &lat, &lon);
		if (rslt != SUCCESS)
			return FAILURE;
	}

	/* DATUM conversion should go here
	--------------------------------*/

	/* 
	The datum conversion facilities should go here 
	*/

	/* Initialize forward transformation
	----------------------------------*/
	if (outinit_flag)
	{
		outpj[*outsys] = *outsys;
		outdat[*outsys] = *outspheroid;
		outzn[*outsys] = *outzone;
		for (i = 0;i < COEFCT; i++)
			pdout[*outsys][i] = m_out_params[i];

		/* If the projection is UTM, copy to a temporary array.  This way, the
		user does not have to enter the zone nor a lat/long within the zone.
		The program will calculate the zone from the input lat/long.
		---------------------------------------------------------------------*/ 
		if (*outsys == PROJ_TYPE_UTM)
		{
			for (i = 2; i < COEFCT; i++)
				temparr[i] = m_out_params[i];
			temparr[0] = 0;
			temparr[1] = 0;
			if (m_out_params[0] == 0.0)
			{
				temparr[0] = pakr2dm(lon);
				temparr[1] = pakr2dm(lat);
			}
			else
			{
				temparr[0] = m_out_params[0];
				temparr[1] = m_out_params[1];
			}
			for_init(*outsys, *outzone, temparr, *outspheroid, &iflg);
		}
		else
			for_init( *outsys, *outzone, m_out_params, *outspheroid, &iflg);
		if (iflg != 0)
		{
			return FAILURE;
		}
	}

	/* Forward transformations
	------------------------*/
	if (*outsys == PROJ_TYPE_GEO)
	{
		outcoor[0] = lon;
		outcoor[1] = lat;
	}
	else
	{
		int rslt;
		double x, y;

		rslt = forward_trans(lat, lon, &x, &y);
		if (rslt != SUCCESS)
			return FAILURE;
		outcoor[0] = x;
		outcoor[1] = y;
	}

	/* find the correct conversion factor for units
	---------------------------------------------*/
	unit = *outunit;
	/* use legislated unit table
	----------------------------*/
	if ((*outspheroid == 0) && (*outsys == PROJ_TYPE_SPCS) && (*outunit == STPLN_TABLE)) 
		unit = 1;
	if ((*outspheroid == 8) && (*outsys == PROJ_TYPE_SPCS) && (*outunit == STPLN_TABLE))
		unit = NADUT[(*outzone)/100];

	if (*outsys == PROJ_TYPE_GEO)
		iflg = untfz(PROJ_UNITS_RADIAN, unit, &factor); 
	else
		iflg = untfz(PROJ_UNITS_METERS, unit, &factor); 

	if (*outsys == PROJ_TYPE_SPCS)
		*outunit = unit;

	outcoor[0] *= factor;
	outcoor[1] *= factor;
	return SUCCESS;
}
