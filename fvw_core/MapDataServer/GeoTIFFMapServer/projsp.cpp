int CProj::get_sp_data(long ind, long sphere, char *pname, int pname_len, long *id, long *units, double *table)
{
	int k;

	if ((ind < 0) || (ind > 133))
		return -1;

   if (sphere == 0)
   {
	   strcpy_s(pname, pname_len, nad27dat[ind].name);
	   *id = nad27dat[ind].id;
	   *units = nad27dat[ind].units;
	   for (k=0; k<9; k++)
			table[k] = nad27dat[ind].table[k];
   }
   else
   {
	   strcpy_s(pname, pname_len, nad83dat[ind].name);
	   *id = nad83dat[ind].id;
	   *units = nad83dat[ind].units;
	   for (k=0; k<9; k++)
			table[k] = nad83dat[ind].table[k];
   }

   return 0;
}

