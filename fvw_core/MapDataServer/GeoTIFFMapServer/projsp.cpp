// Convert DMS packed angle into deg 
int CProj::untfz(long inunit, long outunit, double *factor)
{
	if ((outunit >= 0) && (outunit <= MAXUNIT) && (inunit >= 0) && (inunit <= MAXUNIT))
	{
		*factor = factors[inunit][outunit];
		if (*factor == 0.0)
		{
			m_last_error =  "Uncompatable unit codes";
			return FAILURE;
		}
	}
	else
	{
		m_last_error = "Illegal source or target unit code";
		return(5);
	}

	return SUCCESS;
}

